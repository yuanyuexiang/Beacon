"""从后端 Pydantic 响应契约生成 Places 前端类型；在 apps/api 环境中运行，无网络。"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps/api"))
from app.modules.leads import google_places as routes  # noqa: E402

MODELS = (routes.PlacesState, routes.PlacesSearchOut, routes.PlacesDetailsOut, routes.PlacesLink)
definitions = {}
for model in MODELS:
    schema = model.model_json_schema()
    definitions.update(schema.pop("$defs", {}))
    definitions[model.__name__] = schema


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        required = schema.get("required", [])
        return "{ " + "; ".join(f"{k}{'' if k in required else '?'}: {ts(v)}" for k, v in schema.get("properties", {}).items()) + " }"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


out = ROOT / "apps/web/src/lib/google-places.generated.ts"
out.write_text("// Generated by scripts/generate_places_types.py; edit the backend contract instead.\n" + "\n".join(
    f"export type {name} = {ts(schema)};" for name, schema in sorted(definitions.items())
) + "\n")
print("Generated Places response types")
